#!/usr/bin/env python3
"""Generate FittedAimParams.kt from human_corpus_features.json (spec §11.4).

Run manually whenever the corpus changes:

    python3 tools/human_features.py        # regenerate the JSON first
    python3 tools/gen_fitted_params.py     # then this

Output is deterministic (byte-identical for identical JSON) so diffs are
reviewable. Freshness is enforced by the JUnit FittedParamsSyncTest, which
re-derives every constant from the JSON with the same formulas used here.

Derived constants (formulas are part of the spec, §11.4):
  NOISE_INNOV_*_DEG  = sigma * sqrt(1 - phi^2)          (AR(1) innovation)
  PLAN_DURATION_C_T  = T_p50 / (A_p50 + gcd)^b          (duration law anchor)
  PLAN_SPEED_NORM    = A_p50 / T_p50                    (profile scale = 1 at p50)
"""
import json
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "human_corpus_features.json"
OUT = (ROOT / "src" / "main" / "java" / "net" / "ccbluex" / "liquidbounce"
       / "utils" / "rotation" / "aim" / "FittedAimParams.kt")


def main() -> int:
    if not SRC.exists():
        print(f"missing {SRC} - run tools/human_features.py first")
        return 2
    d = json.loads(SRC.read_text())
    f = d["fitted"]
    hp = d["human"]["pooled"]

    floor = f["noise"]["floor"]
    speed_bins = f["noise"]["by_speed"]["bins"]
    sig_y = floor["position_resid_rms_yaw_deg"]
    sig_p = floor["position_resid_rms_pitch_deg"]
    phi_y = floor["residual_lag1_yaw"]
    phi_p = floor["residual_lag1_pitch"]
    innov_y = sig_y * math.sqrt(1.0 - phi_y * phi_y)
    innov_p = sig_p * math.sqrt(1.0 - phi_p * phi_p)

    eps = f["epochs"]["duration_vs_amplitude_exponent"]
    b = eps["slope"]
    t_p50 = f["epochs"]["duration"]["p50"]
    a_p50 = f["epochs"]["amplitude_net"]["p50"]
    gcd = f["mc"]["gcd"]
    c_t = t_p50 / ((a_p50 + gcd) ** b)
    speed_norm = a_p50 / t_p50

    profile = f["epochs"]["profile_8bin"]
    win = f["mc"]["windowed_std"]
    speed = hp["speed"]

    def fl(v: float) -> str:
        return f"{float(v)!r}f"

    def arr(vals) -> str:
        return ", ".join(fl(v) for v in vals)

    lines = [
        "package net.ccbluex.liquidbounce.utils.rotation.aim",
        "",
        "/**",
        " * GENERATED by tools/gen_fitted_params.py - do not edit by hand.",
        " * Source:  tools/human_corpus_features.json (regenerate that first).",
        " * Manifest: tools/human_corpus_findings.md §11.4.",
        " * Freshness is enforced by FittedParamsSyncTest.",
        " */",
        "object FittedAimParams {",
        "    // stage 4 - colored noise (fitted.noise.floor.*)",
        f"    const val NOISE_SIGMA_YAW_DEG = {fl(sig_y)}",
        f"    const val NOISE_SIGMA_PITCH_DEG = {fl(sig_p)}",
        f"    const val NOISE_PHI_YAW = {fl(phi_y)}",
        f"    const val NOISE_PHI_PITCH = {fl(phi_p)}",
        f"    const val NOISE_INNOV_YAW_DEG = {fl(innov_y)}",
        f"    const val NOISE_INNOV_PITCH_DEG = {fl(innov_p)}",
        f"    val NOISE_BIN_MAX_DEG = floatArrayOf({arr([b['max_speed'] for b in speed_bins])})",
        f"    val NOISE_BIN_SIGMA_YAW_DEG = floatArrayOf({arr([b['sigma_yaw'] for b in speed_bins])})",
        f"    val NOISE_BIN_SIGMA_PITCH_DEG = floatArrayOf({arr([b['sigma_pitch'] for b in speed_bins])})",
        "",
        "    // stage 2 - motor plan (fitted.epochs.*)",
        f"    const val PLAN_DURATION_EXP_B = {fl(b)}",
        f"    const val PLAN_DURATION_C_T = {fl(c_t)}",
        f"    const val PLAN_SPEED_NORM = {fl(speed_norm)}",
        f"    val PLAN_PROFILE_8BIN = floatArrayOf({arr(profile)})",
        f"    const val PLAN_FITTS_SLOPE = {fl(f['epochs']['fitts_peak_vs_log2_amp']['slope'])}",
        f"    const val PLAN_FLICK_SLOPE = {fl(f['epochs']['peak_vs_amplitude_A15']['slope'])}",
        f"    const val PLAN_FLICK_BASE = {fl(f['epochs']['peak_vs_amplitude_A15']['intercept'])}",
        f"    const val PLAN_TAU_PEAK_DIAG = {fl(f['epochs']['time_to_peak_tau']['mean'])}",
        "",
        "    // stage 5 - event scheduler (fitted.dwell, fitted.epochs)",
        f"    const val SCHED_DWELL_MEAN = {fl(f['dwell']['mean_ticks'])}",
        f"    const val SCHED_DWELL_P90 = {fl(f['dwell']['p90_ticks'])}",
        f"    const val SCHED_EPOCH_RATE = {fl(f['epochs']['rate_per_s'])}",
        "",
        "    // stage 3 - servo limits (human.pooled.*)",
        f"    const val SERVO_SPEED_P50 = {fl(speed['p50'])}",
        f"    const val SERVO_SPEED_P90 = {fl(speed['p90'])}",
        f"    const val SERVO_SPEED_P99 = {fl(speed['p99'])}",
        f"    const val SERVO_SPEED_MAX = {fl(speed['max'])}",
        f"    const val SERVO_PEAK_P90 = {fl(hp['epochs']['peak_speed']['p90'])}",
        f"    const val SERVO_WIN_STD_P90_5 = {fl(win['5']['std']['p90'])}",
        f"    const val SERVO_WIN_STD_P90_10 = {fl(win['10']['std']['p90'])}",
        f"    const val SERVO_WIN_STD_P90_20 = {fl(win['20']['std']['p90'])}",
        "",
        "    // stage 1 - corrections (fitted.correction.*)",
        f"    const val CORRECTION_MICRO_FRAC = {fl(f['correction']['micro_frac_nonzero'])}",
        f"    const val CORRECTION_REVERSALS_MEAN = {fl(f['correction']['reversals_per_epoch']['mean'])}",
        "",
        "    // stage 6 - quantizer target (human.pooled.grid_residual_steps.p99)",
        f"    const val QUANT_TARGET_STEPS = {fl(hp['grid_residual_steps']['p99'])}",
        "",
        "    // acceptance baselines (harness derives the same from the JSON)",
        f"    const val ACCEPT_LAG1_YAW = {fl(hp['lag1_yaw_delta'])}",
        f"    const val ACCEPT_LAG1_PITCH = {fl(hp['lag1_pitch_delta'])}",
        f"    const val ACCEPT_MINJERK_R2 = {fl(hp['epochs']['minjerk_r2'])}",
        f"    const val ACCEPT_END_FLIP = {fl(f['correction']['end_flip_rate'])}",
        "}",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(lines) - 1} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
